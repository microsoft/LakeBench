import logging
import math
import shutil
import subprocess
import sysconfig
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple
from urllib.parse import urlparse
from urllib.request import url2pathname

logger = logging.getLogger(__name__)


class TpcgenDataGenerator:
    """Generate TPC data with ``tpcgen-cli``, as ``<target>/<table>/<table>.<part>.<parquet|tbl|dat>``."""

    #: tpcgen-cli benchmark subcommand.
    BENCHMARK = ""
    #: tpcgen-cli subcommand and file extension of the native pipe-delimited format.
    NATIVE_FORMAT = ""
    #: Measured size of each table at SF10, in MiB, as (ZSTD(1) Parquet, native).
    #: Used only to choose how many files to split each table into.
    SF10_SIZE_MIB: Dict[str, Tuple[float, float]] = {}
    #: Default ``--row-group-bytes`` (uncompressed), giving the largest tables
    #: ~128 MiB ZSTD(1) row groups on disk.
    ROW_GROUP_MIB = 128
    #: File size by estimated table size: 128 MiB below 10 GiB, 256 MiB below 1 TiB,
    #: 512 MiB below 5 TiB, then 1 GiB.
    FILE_SIZE_STEPS_MIB = ((10 * 1024, 128), (1024**2, 256), (5 * 1024**2, 512))

    def __init__(
        self,
        scale_factor: float,
        target_folder_uri: str,
        target_row_group_size_mb: Optional[int] = None,
        compression: Optional[str] = None,
        table_list: Optional[List[str]] = None,
        num_threads: Optional[int] = None,
        output_format: str = "parquet",
    ) -> None:
        """
        Parameters
        ----------
        scale_factor : float
            Scale factor that determines the generated dataset size.
        target_folder_uri : str
            Local or mounted folder. Each table is written to its own subfolder.
        target_row_group_size_mb : int, optional
            Approximate uncompressed Parquet row-group size in MiB, passed to
            ``--row-group-bytes``. Defaults to ``ROW_GROUP_MIB``, which gives the largest
            tables ~128 MiB row groups on disk with ZSTD(1).
        compression : str, default="ZSTD(1)"
            Parquet compression codec, for example ``"SNAPPY"`` or ``"ZSTD(3)"``.
        table_list : list of str, optional
            Tables to generate. All tables are generated by default.
        num_threads : int, optional
            Generator thread count. Defaults to all available CPU cores. Use a lower
            value such as 8 or 16 for large generations targeting mounted filesystems.
        output_format : {"parquet", "native"}, default="parquet"
            ``"native"`` writes the pipe-delimited ``.tbl`` (TPC-H) or ``.dat`` (TPC-DS)
            format. ``target_row_group_size_mb`` and ``compression`` apply only to Parquet.
        """
        if output_format not in ("parquet", "native"):
            raise ValueError("output_format must be either 'parquet' or 'native'.")
        if output_format == "native" and (target_row_group_size_mb is not None or compression is not None):
            raise ValueError("target_row_group_size_mb and compression apply only to output_format='parquet'.")
        table_list = list(self.SF10_SIZE_MIB if table_list is None else table_list)
        if not table_list:
            raise ValueError("table_list must contain at least one table.")
        unknown_tables = sorted(set(table_list) - set(self.SF10_SIZE_MIB))
        if unknown_tables:
            raise ValueError(f"Unsupported {self.BENCHMARK} tables: {', '.join(unknown_tables)}")

        self.scale_factor = scale_factor
        self.target_folder = _local_path(target_folder_uri)
        self.target_row_group_size_mb = target_row_group_size_mb or self.ROW_GROUP_MIB
        self.compression = compression or "ZSTD(1)"
        self.table_list = table_list
        self.num_threads = num_threads
        self.output_format = output_format
        self.executable = _find_executable()
        self.parts_by_table = {table: self._parts(table) for table in table_list}

    def _parts(self, table: str) -> int:
        size_mib = self.SF10_SIZE_MIB[table][self.output_format == "native"] * self._growth(table)
        file_size_mib = next((mib for limit, mib in self.FILE_SIZE_STEPS_MIB if size_mib < limit), 1024)
        return max(1, math.ceil(size_mib / file_size_mib))

    def _growth(self, table: str) -> float:
        """Return the table's row count at ``scale_factor`` relative to SF10."""
        return self.scale_factor / 10

    def run(self) -> None:
        self.target_folder.mkdir(parents=True, exist_ok=True)
        tables_by_parts = defaultdict(list)
        for table in self.table_list:
            # tpcgen-cli skips files that already exist; clear any previous output.
            table_folder = self.target_folder / table
            if table_folder.exists():
                shutil.rmtree(table_folder)
            tables_by_parts[self.parts_by_table[table]].append(table)
        for parts, tables in tables_by_parts.items():
            logger.info("Generating %s tables %s with %d part(s).", self.BENCHMARK, ", ".join(tables), parts)
            _run(self._command(tables, parts))

    def _command(self, tables: List[str], parts: int) -> List[str]:
        command = [
            self.executable,
            self.BENCHMARK,
            "parquet" if self.output_format == "parquet" else self.NATIVE_FORMAT,
            "--scale-factor",
            str(self.scale_factor),
            "--output-dir",
            str(self.target_folder),
            "--tables",
            ",".join(tables),
            "--parts",
            str(parts),
        ]
        if self.output_format == "parquet":
            command += ["--compression", self.compression, "--row-group-bytes", f"{self.target_row_group_size_mb}MiB"]
        if self.num_threads is not None:
            command += ["--num-threads", str(self.num_threads)]
        return command


def _local_path(uri: str) -> Path:
    parsed = urlparse(uri)
    if parsed.scheme == "file":
        return Path(url2pathname(f"//{parsed.netloc}{parsed.path}")).resolve()
    if "://" in uri:
        raise ValueError(f"tpcgen-cli writes to local or mounted paths only, not {parsed.scheme}:// URIs.")
    return Path(uri).expanduser().resolve()


def _find_executable() -> str:
    # Prefer the running interpreter's scripts directory: notebook kernels often
    # do not have the environment's bin directory on PATH.
    executable = shutil.which("tpcgen-cli", path=sysconfig.get_path("scripts")) or shutil.which("tpcgen-cli")
    if executable is None:
        raise ImportError(
            "tpcgen-cli is not installed. Install it with `pip install lakebench[tpch_datagen]` or "
            "`pip install lakebench[tpcds_datagen]`."
        )
    return executable


def _run(command: List[str]) -> None:
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=True)
    except subprocess.CalledProcessError as exc:
        details = [f"tpcgen-cli failed with exit code {exc.returncode}: {' '.join(command)}"]
        if exc.stdout:
            details.append(f"stdout:\n{exc.stdout.rstrip()}")
        if exc.stderr:
            details.append(f"stderr:\n{exc.stderr.rstrip()}")
            if "Failed to rename" in exc.stderr:
                details.append(
                    "Mounted filesystems can fail under concurrent file renames. Retry with a lower "
                    "num_threads value, such as num_threads=8 or num_threads=16."
                )
        raise RuntimeError("\n".join(details)) from exc
    for output in (result.stdout, result.stderr):
        if output:
            logger.info(output.rstrip())
